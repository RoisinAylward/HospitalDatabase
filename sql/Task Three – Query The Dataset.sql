-- Query 17:
SELECT p.PFORENAME AS FirstName,
    p.PSURNAME AS LastName,
    mh.CONDITIONNAME AS MedicalCondition,
    mh.RECORDDATE AS RecordDate,
    a.DATE AS Appointment_Date,
    a.TIME AS Appointment_Time,
    t.TNAME AS Treatment_Name
FROM PATIENT p
LEFT JOIN MEDICAL_HISTORY mh ON p.PATIENTID = mh.PATIENTID
LEFT JOIN APPT a ON p.PATIENTID = a.PATIENTID
LEFT JOIN APPT_TREATMENT at ON a.APPTID = at.APPTID
LEFT JOIN TREATMENT t ON at.TREATNO = t.TREATNO
ORDER BY p.PFORENAME, p.PSURNAME, a.DATE;

