-- Query 19:
CREATE VIEW Patient_Dept_Contact AS
SELECT p.PFORENAME AS FirstName,
    p.PSURNAME AS LastName,
    dp.BEDNO AS BedNumber,
    dp.ADMISSION_DATE AS Admission_Date,
    pc.PHONE AS Phone,
    pc.EMAIL AS Email,
    pc.ADDRESS1 AS Address1,
    pc.ADDRESS2 AS Address2,
    pc.COUNTY AS County,
    pc.EIRCODE AS Eircode
FROM PATIENT p
JOIN DEPT_PATIENT dp ON p.PATIENTID = dp.PATIENTID
JOIN PATIENT_CONTACT pc ON p.PATIENTID = pc.PATIENTID;

SELECT * FROM Patient_Dept_Contact;

