CREATE TABLE DEPT (
 DEPTNO              INT NOT NULL,
 DNAME               VARCHAR(20),
 LOC				 VARCHAR(12),
 BEDCAP				 INT,
 PHONE				 VARCHAR(9),
 EMAIL				 VARCHAR(30),
 CONSTRAINT DEPT_PRIMARY_KEY PRIMARY KEY (DEPTNO));

CREATE TABLE TREATMENT (
 TREATNO             INT NOT NULL,
 TNAME               VARCHAR(40),
 DEPTNO				 INT NOT NULL,
 CONSTRAINT TREATMENT_DEPTNO_FK FOREIGN KEY (DEPTNO) REFERENCES DEPT (DEPTNO),
 CONSTRAINT TREATMENT_PRIMARY_KEY PRIMARY KEY (TREATNO));

CREATE TABLE STAFF (
 STAFFID             INT NOT NULL,
 SFORENAME           VARCHAR(20),
 SSURNAME			 VARCHAR(20),
 JOB                 VARCHAR(30),
 DEPTNO				 INT,
 PHONE				 INT,
 EMAIL				 VARCHAR(30),
 HIREDATE            DATE,
 DAYSOFF			 INT,
 CONSTRAINT STAFF_DEPTNO_FK FOREIGN KEY (DEPTNO) REFERENCES DEPT (DEPTNO),
 CONSTRAINT STAFF_PRIMARY_KEY PRIMARY KEY (STAFFID));

CREATE TABLE PATIENT (
 PATIENTID           INT NOT NULL,
 PFORENAME           VARCHAR(20),
 PSURNAME			 VARCHAR(20),
 DOB				 DATE,
 SEX                 VARCHAR(1),
 CONSTRAINT PATIENT_PRIMARY_KEY PRIMARY KEY (PATIENTID));

CREATE TABLE DEPT_PATIENT (
 DEPTNO				 INT NOT NULL,
 BEDNO				 INT NOT NULL,
 PATIENTID		 	 INT,
 ADMISSION_DATE		 DATE,
 CONSTRAINT DEPT_PATIENT_DEPT_FK FOREIGN KEY (DEPTNO) REFERENCES DEPT(DEPTNO),
 CONSTRAINT DEPT_PATIENT_PATIENT_FK FOREIGN KEY (PATIENTID) REFERENCES PATIENT(PATIENTID),
 CONSTRAINT DEPT_PATIENT_PRIMARY_KEY PRIMARY KEY (DEPTNO,BEDNO));

CREATE TABLE MEDICAL_HISTORY (
 PATIENTID           INT NOT NULL,
 CONDITIONNAME 		 VARCHAR(40),
 RECORDDATE			 DATE,
 CONDITIONSTATUS     VARCHAR(10),
 CONSTRAINT MEDICAL_HISTORY_PATIENT_FK FOREIGN KEY (PATIENTID) REFERENCES PATIENT (PATIENTID),
 CONSTRAINT MEDICAL_HISTORY_PRIMARY_KEY PRIMARY KEY (PATIENTID,CONDITIONNAME,RECORDDATE));

CREATE TABLE PATIENT_CONTACT (
 PATIENTID           INT NOT NULL,
 PHONE				 INT,
 EMAIL				 VARCHAR(35),
 ADDRESS1			 VARCHAR(30),
 ADDRESS2			 VARCHAR(30),
 COUNTY				 VARCHAR(9),
 EIRCODE			 VARCHAR(8),
 CONSTRAINT PATIENT_CONTACT_PATIENT_FK FOREIGN KEY (PATIENTID) REFERENCES PATIENT (PATIENTID),
 CONSTRAINT PATIENT_PRIMARY_KEY PRIMARY KEY (PATIENTID));

CREATE TABLE APPT (
 APPTID				 INT NOT NULL,
 DEPTNO				 INT NOT NULL,
 PATIENTID           INT NOT NULL,
 DATE				 DATE,
 TIME                TIME,
 STATUS				 VARCHAR(20),
 CONSTRAINT APPT_PRIMARY_KEY PRIMARY KEY (APPTID));
 
CREATE TABLE APPT_STAFF (
 APPTID				 INT NOT NULL,
 STAFFID			 INT NOT NULL,
 CONSTRAINT APPT_STAFF_APPT_FK FOREIGN KEY (APPTID) REFERENCES APPT (APPTID),
 CONSTRAINT APPT_STAFF_STAFF_FK FOREIGN KEY (STAFFID) REFERENCES STAFF (STAFFID),
 CONSTRAINT APPT_PRIMARY_KEY PRIMARY KEY (APPTID,STAFFID));

CREATE TABLE APPT_TREATMENT (
 APPTID				 INT NOT NULL,
 TREATNO		 	 INT NOT NULL,
 CONSTRAINT APPT_TREATMENT_APPT_FK FOREIGN KEY (APPTID) REFERENCES APPT (APPTID),
 CONSTRAINT APPT_TREATMENT_TREATMENT_FK FOREIGN KEY (TREATNO) REFERENCES TREATMENT (TREATNO),
 CONSTRAINT APPT_PRIMARY_KEY PRIMARY KEY (APPTID,TREATNO));


